import type { Dirent } from "node:fs";
import {
  mkdir,
  mkdtemp,
  readFile,
  readdir,
  rm,
  writeFile,
} from "node:fs/promises";
import path from "node:path";

import { validateFunctionName } from "@patchsmith/app/server";

import { resolveAppSourceRoot } from "#source-root";

import { isMissingFile } from "./fs-errors";
import { watchSourceDirectory } from "./watch-source-directory";

const functionPathSeparator = /[./\\]/u;

export interface FunctionFile {
  filename: string;
  path: string[];
}

/** Only .router.ts modules register functions; dots and directories separate namespaces. */
export const discoverFunctionFiles = async (
  root: string
): Promise<FunctionFile[]> => {
  const directory = path.join(resolveAppSourceRoot(root), "functions");
  let entries: Dirent[];

  try {
    entries = await readdir(directory, {
      recursive: true,
      withFileTypes: true,
    });
  } catch (error) {
    if (isMissingFile(error)) {
      return [];
    }

    throw error;
  }

  const files: FunctionFile[] = [];

  const filenames = entries
    .filter((entry) => entry.isFile() && entry.name.endsWith(".router.ts"))
    .map((entry) =>
      path.relative(directory, path.join(entry.parentPath, entry.name))
    )
    .toSorted();

  for (const entry of filenames) {
    const filename = path.join(directory, entry);

    const segments = entry
      .slice(0, -".router.ts".length)
      .split(functionPathSeparator);

    for (const segment of segments) {
      try {
        validateFunctionName(segment);
      } catch (error) {
        throw new Error(
          `${filename}: ${error instanceof Error ? error.message : String(error)}`,
          { cause: error }
        );
      }
    }

    files.push({ filename, path: segments });
  }

  return files;
};

const moduleSpecifier = (filename: string, importer: string) => {
  const relative = path
    .relative(path.dirname(importer), filename)
    .split(path.sep)
    .join("/")
    .replace(/\.ts$/u, "");

  return relative.startsWith(".") ? relative : `./${relative}`;
};

/** Type-only imports preserve inference without loading private server code. */
export const renderFunctionTypes = (
  files: readonly FunctionFile[],
  output: string
): string => {
  const imports = files.map(
    (file, index) =>
      `import type module${index} from ${JSON.stringify(moduleSpecifier(file.filename, output))};`
  );

  const namespaces = files.map((file, index) => {
    let type = `typeof module${index}`;

    for (const name of file.path.toReversed()) {
      type = `{ readonly ${JSON.stringify(name)}: ${type} }`;
    }

    return type;
  });

  return `// Generated by Patchsmith. Do not edit.\n${imports.join("\n")}\nexport type AppServerFunctions = ${namespaces.join(" & ") || "Record<never, never>"};\n`;
};

const writeChangedFile = async (filename: string, source: string) => {
  const current = await readFile(filename, "utf-8").catch(
    (error: ErrorOptions["cause"]) => {
      if (isMissingFile(error)) {
        return;
      }

      throw error;
    }
  );

  if (current !== source) {
    await mkdir(path.dirname(filename), { recursive: true });
    await writeFile(filename, source);
  }
};

export const generateFunctionTypes = async (
  root: string,
  files: readonly FunctionFile[]
) => {
  const output = path.join(
    resolveAppSourceRoot(root),
    "patchsmith.functions.gen.ts"
  );

  await writeChangedFile(output, renderFunctionTypes(files, output));

  return output;
};

const fileServerSource = (root: string, files: readonly FunctionFile[]) => {
  const imports = files.map(
    (file, index) =>
      `import module${index} from ${JSON.stringify(file.filename)};`
  );

  const modules = files.map(
    (file, index) =>
      `{ filename: ${JSON.stringify(path.relative(root, file.filename))}, path: ${JSON.stringify(file.path)}, functions: module${index} }`
  );

  return `import { createFileServer } from "patchsmith/server";\n${imports.join("\n")}\nexport default createFileServer([${modules.join(",")}]);\n`;
};

/** Keep the private registry and type bindings current when files are added or removed. */
export const createFileFunctionEntry = async (
  root: string,
  output: string,
  watching: boolean
) => {
  const files = await discoverFunctionFiles(root);
  await generateFunctionTypes(root, files);
  const temporaryRoot = path.join(output, "tmp");
  await mkdir(temporaryRoot, { recursive: true });
  const directory = await mkdtemp(path.join(temporaryRoot, "functions-"));
  const entry = path.join(directory, "entry.ts");
  await writeChangedFile(entry, fileServerSource(root, files));
  let pending = Promise.resolve();
  let timer: ReturnType<typeof setTimeout> | undefined;
  let closed = false;

  const refresh = async () => {
    if (closed) {
      return;
    }

    try {
      const next = await discoverFunctionFiles(root);
      await generateFunctionTypes(root, next);
      await writeChangedFile(entry, fileServerSource(root, next));
    } catch (error) {
      await writeChangedFile(
        entry,
        `throw new Error(${JSON.stringify(error instanceof Error ? error.message : String(error))}); export default undefined;`
      );
    }
  };

  const watcher = watching
    ? watchSourceDirectory(resolveAppSourceRoot(root), "functions", () => {
        if (timer) {
          clearTimeout(timer);
        }

        timer = setTimeout(() => {
          pending = (async () => {
            await pending;
            await refresh();
          })();
        }, 25);
      })
    : undefined;

  return {
    close: async () => {
      closed = true;

      if (timer) {
        clearTimeout(timer);
      }

      watcher?.close();

      try {
        await pending;
      } finally {
        await rm(directory, { force: true, recursive: true });
      }
    },
    entry,
  };
};
